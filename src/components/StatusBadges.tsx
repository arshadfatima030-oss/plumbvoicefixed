export function TradeLabel({trade}: {trade: TradeCategory}) {
  return (
    <span className="inline-flex items-center gap-1 text-[12px] font-medium text-[#7A746B]">
      {trade === 'Electrical' ? (
        <Zap className="w-3.5 h-3.5 text-[#F2A93B]" aria-hidden="true" />
      ) : (
        <Wrench className="w-3.5 h-3.5 text-[#C8672B]" aria-hidden="true" />
      )}
      <span>{trade}</span>
    </span>
  );
}

export function formatDuration(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60);
  return `${m}:${s.toString().padStart(2, '0')}`;
}

export function formatCurrency(amount: number): string {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(amount);
}

